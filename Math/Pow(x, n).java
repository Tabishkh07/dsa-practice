/*
Problem: <50: Pow(x, n)>
Topic: <Math Calculation>
Approach: <Brute Force - Using math function>
Time Complexity: O(1)
Space Complexity: O(1)
*/

class Solution {
    public double myPow(double x, int n) {
        return (double) Math.pow(x, n);
    }
}

